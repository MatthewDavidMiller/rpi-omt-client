"""Generate the VMX entropy decoder's twelve-bit lookahead table.

The AC stream of a VMX1 plane is a sequence of three code shapes, read MSB
first (src/vmx/plane.c reads them one bit field at a time):

    11                          one zero coefficient
    10 0{z} 1 b{z+1}            a run of zeros, the run being 1b{z+1}
    0  0{z} 1 b{z+1}            one coefficient, GetIntFrom2MagSign(1b{z+1} - 1)

Every code no longer than twelve bits is resolved here in one lookup on the
next twelve bits of the stream. An entry packs the payload (the coefficient,
or the zero count) into bits 0..15, the code length into bits 16..23, and the
kind into bits 24..25; zero means the code is longer and the decoder takes
the bit-by-bit path, which is unchanged.

    gen_vmx_tables.py           write src/vmx/ac_lookahead.c
    gen_vmx_tables.py --check   fail if the committed file differs
"""

import argparse
import pathlib
import sys

BITS = 12
KIND_ZEROS = 1
KIND_VALUE = 2
OUTPUT = pathlib.Path(__file__).resolve().parents[2] / "src/vmx/ac_lookahead.c"


def mag_sign(value: int) -> int:
    """vmx_mag_sign: GetIntFrom2MagSign(value - 1), truncated to 16 bits."""
    mask = (1 << 64) - 1
    raw = (value - 1) & mask
    parity = raw & 1
    adjusted = (raw + parity) & mask
    return (((adjusted >> 1) - adjusted * parity) & mask) & 0xFFFF


def golomb(bits: str, start: int) -> tuple[int, int] | None:
    """The z zeros, the 1, and z+1 more bits at `start`: (end, value)."""
    zeros = 0
    while start + zeros < len(bits) and bits[start + zeros] == "0":
        zeros += 1
    end = start + zeros + zeros + 2
    if end > len(bits):
        return None
    return end, int(bits[start + zeros : end], 2)


def entry(index: int) -> int:
    bits = format(index, f"0{BITS}b")
    if bits[0] == "1":
        if bits[1] == "1":
            return KIND_ZEROS << 24 | 2 << 16 | 1
        code = golomb(bits, 2)
        if code is None:
            return 0
        length, run = code
        return KIND_ZEROS << 24 | length << 16 | run
    code = golomb(bits, 1)
    if code is None:
        return 0
    length, value = code
    return KIND_VALUE << 24 | length << 16 | mag_sign(value)


def render() -> str:
    table = [entry(i) for i in range(1 << BITS)]
    # Anchors: "11" is a lone zero; "010" and "011" are the coefficients -1
    # and +1; "1010" is a run of two; twelve zeros are too long to resolve.
    assert table[0b110000000000] == KIND_ZEROS << 24 | 2 << 16 | 1
    assert table[0b010000000000] == KIND_VALUE << 24 | 3 << 16 | 0xFFFF
    assert table[0b011000000000] == KIND_VALUE << 24 | 3 << 16 | 1
    assert table[0b101000000000] == KIND_ZEROS << 24 | 4 << 16 | 2
    assert table[0] == 0
    lines = [
        "/* Copyright (c) 2026 Matthew David Miller",
        " * SPDX-License-Identifier: MIT",
        " *",
        " * @generated by tools/gen/gen_vmx_tables.py. Do not edit.",
        " *",
        " * The AC lookahead table; the generator documents the entry format.",
        " */",
        '#include "vmx/plane.h"',
        "",
        f"const uint32_t vmx_ac_lookahead[{1 << BITS}] = {{",
    ]
    for i in range(0, len(table), 6):
        row = ", ".join(f"0x{v:08x}u" for v in table[i : i + 6])
        lines.append(f"    {row},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed file differs")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f"{OUTPUT} is stale: run tools/gen/gen_vmx_tables.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
