"""Generate Blowfish's initial P-array and S-boxes for bcrypt_pbkdf.

Blowfish starts from the fractional hexadecimal digits of pi: the 18 P-array
words and then the four 256-word S-boxes, 1042 words in all. They are computed
here from Machin's formula with exact integer arithmetic rather than copied
from somewhere, and checked against the published first and last words.

    gen_blowfish_tables.py           write crates/omt-deploy/src/ssh/blowfish_tables.rs
    gen_blowfish_tables.py --check   fail if the committed file differs
"""

import argparse
import pathlib
import sys

WORDS = 18 + 4 * 256
ROOT = pathlib.Path(__file__).resolve().parents[2]
RUST_OUTPUT = ROOT / "crates/omt-deploy/src/ssh/blowfish_tables.rs"


def arctan_inverse(x: int, scale: int) -> int:
    """arctan(1/x) * scale, by its Taylor series."""
    total = term = scale // x
    x2 = x * x
    n = 1
    sign = -1
    while term:
        term //= x2
        total += sign * (term // (2 * n + 1))
        sign = -sign
        n += 1
    return total


def pi_words() -> list[int]:
    bits = WORDS * 32
    guard = 64
    scale = 1 << (bits + guard)
    pi = 16 * arctan_inverse(5, scale) - 4 * arctan_inverse(239, scale)
    fraction = (pi >> guard) - (3 << bits)
    return [(fraction >> (32 * (WORDS - 1 - i))) & 0xFFFFFFFF for i in range(WORDS)]


def render_rust(words: list[int]) -> str:
    # Published anchors: P[0], P[17], S[0][0], and S[3][255].
    assert words[0] == 0x243F6A88, hex(words[0])
    assert words[17] == 0x8979FB1B, hex(words[17])
    assert words[18] == 0xD1310BA6, hex(words[18])
    assert words[-1] == 0x3AC372E6, hex(words[-1])
    lines = [
        "// @generated by tools/gen/gen_blowfish_tables.py. Do not edit.",
        "//",
        "// Blowfish's initial state: the fractional hexadecimal digits of pi.",
        "",
        "pub(super) const INIT_P: [u32; 18] = [",
    ]

    def block(values: list[int], indent: str) -> None:
        for i in range(0, len(values), 6):
            row = ", ".join(f"0x{v >> 16:04x}_{v & 0xFFFF:04x}" for v in values[i : i + 6])
            lines.append(f"{indent}{row},")

    block(words[:18], "    ")
    lines.append("];")
    lines.append("")
    lines.append("pub(super) const INIT_S: [[u32; 256]; 4] = [")
    for box in range(4):
        lines.append("    [")
        start = 18 + 256 * box
        block(words[start : start + 256], "        ")
        lines.append("    ],")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    words = pi_words()
    outputs = {RUST_OUTPUT: render_rust(words)}
    if arguments.check:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        for path in stale:
            print(f"{path} is stale; run {__file__}", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
