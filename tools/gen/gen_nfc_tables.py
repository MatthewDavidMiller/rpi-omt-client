"""Generate the NFC tables from the committed Unicode extract.

The output is crates/omt-common/src/nfc_tables.rs.

The Rust validator used unicode-normalization 0.1.24, which carries Unicode
16.0.0; the extract in third_party/unicode/16.0.0 pins the same version (see
tools/gen/extract_ucd.py for how it was produced). `--check` regenerates in
memory and fails when the committed tables differ, so a hand edit is caught
by the gate.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
UNICODE_VERSION = "16.0.0"
SOURCE = ROOT / f"third_party/unicode/{UNICODE_VERSION}/nfc-data.txt"
RUST_OUTPUT = ROOT / "crates/omt-common/src/nfc_tables.rs"


def tables() -> tuple[list, list, list]:
    ccc, decomp, comp = [], [], []
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        cp_text, cls_text, mapping_text, primary_text = line.split(";")
        cp, cls = int(cp_text, 16), int(cls_text)
        if cls:
            ccc.append((cp, cls))
        if mapping_text:
            parts = [int(p, 16) for p in mapping_text.split()]
            if len(parts) > 2:
                raise SystemExit(f"U+{cp:04X}: canonical mapping longer than two")
            decomp.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
            if primary_text == "1":
                comp.append((parts[0], parts[1], cp))
    comp.sort()
    return ccc, decomp, comp


def render_rust() -> str:
    ccc, decomp, comp = tables()
    lines = [
        f"// Generated by tools/gen/gen_nfc_tables.py from Unicode {UNICODE_VERSION}. Do not edit.",
        "",
        "/// Canonical combining classes of every code point whose class is not 0.",
        f"pub(crate) static CCC: [(u32, u8); {len(ccc)}] = [",
    ]
    lines += [f"    (0x{cp:05X}, {cls})," for cp, cls in ccc]
    lines += [
        "];",
        "",
        "/// Canonical decompositions: code point, first, second (0 for a singleton).",
    ]
    lines += [f"pub(crate) static DECOMP: [(u32, u32, u32); {len(decomp)}] = ["]
    lines += [f"    (0x{cp:05X}, 0x{a:05X}, 0x{b:05X})," for cp, a, b in decomp]
    lines += ["];", "", "/// Primary composites: first, second, composite; sorted by the pair."]
    lines += [f"pub(crate) static COMP: [(u32, u32, u32); {len(comp)}] = ["]
    lines += [f"    (0x{a:05X}, 0x{b:05X}, 0x{cp:05X})," for a, b, cp in comp]
    lines += ["];", ""]
    return "\n".join(lines)


def main() -> int:
    outputs = {RUST_OUTPUT: render_rust()}
    if sys.argv[1:] == ["--check"]:
        stale = [
            path
            for path, text in outputs.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        for path in stale:
            print(f"{path} is stale; run {sys.argv[0]}", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
