"""Generate src/common/nfc_tables.c from the committed Unicode extract.

The Rust validator used unicode-normalization 0.1.24, which carries Unicode
16.0.0; the extract in third_party/unicode/16.0.0 pins the same version (see
tools/gen/extract_ucd.py for how it was produced). `--check` regenerates in
memory and fails when the committed tables differ, so a hand edit to either
file is caught by the gate.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
UNICODE_VERSION = "16.0.0"
SOURCE = ROOT / f"third_party/unicode/{UNICODE_VERSION}/nfc-data.txt"
OUTPUT = ROOT / "src/common/nfc_tables.c"


def render() -> str:
    ccc, decomp, comp = [], [], []
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        cp_text, cls_text, mapping_text, primary_text = line.split(";")
        cp, cls = int(cp_text, 16), int(cls_text)
        if cls:
            ccc.append((cp, cls))
        if mapping_text:
            parts = [int(p, 16) for p in mapping_text.split()]
            if len(parts) > 2:
                raise SystemExit(f"U+{cp:04X}: canonical mapping longer than two")
            decomp.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
            if primary_text == "1":
                comp.append((parts[0], parts[1], cp))
    comp.sort()
    lines = [
        "/* Generated by tools/gen/gen_nfc_tables.py from Unicode "
        f"{UNICODE_VERSION}. Do not edit. */",
        '#include "common/nfc_tables.h"',
        "",
        f"const omt_nfc_ccc omt_nfc_ccc_table[{len(ccc)}] = {{",
    ]
    lines += [f"    {{0x{cp:05X}, {cls}}}," for cp, cls in ccc]
    lines += ["};", "", f"const omt_nfc_decomp omt_nfc_decomp_table[{len(decomp)}] = {{"]
    lines += [f"    {{0x{cp:05X}, 0x{a:05X}, 0x{b:05X}}}," for cp, a, b in decomp]
    lines += ["};", "", f"const omt_nfc_comp omt_nfc_comp_table[{len(comp)}] = {{"]
    lines += [f"    {{0x{a:05X}, 0x{b:05X}, 0x{cp:05X}}}," for a, b, cp in comp]
    lines += [
        "};",
        "",
        f"const size_t omt_nfc_ccc_count = {len(ccc)};",
        f"const size_t omt_nfc_decomp_count = {len(decomp)};",
        f"const size_t omt_nfc_comp_count = {len(comp)};",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if sys.argv[1:] == ["--check"]:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT} is stale; run {sys.argv[0]}", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
