"""Compile the manifest-v3 capsule into the deployer.

Everything the Raspberry Pi receives -- the host scripts, the OpenRC services,
the compose file, the legal texts, and the ARM64 image archive -- is embedded,
so the operator's copy of the deployer is the whole appliance and needs no
checkout beside it.

deploy/manifest-v3.txt stays the single definition of that set: this reads it
and writes an assembler file that pulls each member in with .incbin, plus the
table src/deploy/core/capsule.c reads. The archive is tens of megabytes, and
.incbin copies it straight into the object file instead of through a C array
the compiler would have to parse.

    gen_capsule.py --root DIR --format elf|pe --output FILE.S
                   [--depfile FILE.d --object FILE.o]
"""

import argparse
import pathlib
import re
import sys

MAX_MEMBERS = 128
SAFE = re.compile(r"[A-Za-z0-9._/-]+")


def fail(message: str) -> "None":
    print(f"error: {message}", file=sys.stderr)
    sys.exit(1)


def safe_member(value: str) -> bool:
    """The same rule as dp_valid_manifest_name in src/deploy/core/core.c."""
    return (
        0 < len(value) <= 240
        and not value.startswith("/")
        and not value.endswith("/")
        and "//" not in value
        and SAFE.fullmatch(value) is not None
        and all(part not in ("", ".", "..") for part in value.split("/"))
    )


def read_members(root: pathlib.Path) -> list[str]:
    manifest = root / "deploy/manifest-v3.txt"
    try:
        lines = manifest.read_text(encoding="utf-8").splitlines()
    except OSError as error:
        fail(f"{manifest} is unreadable: {error}")
    if not lines or lines[0] != "version=3":
        fail(f"{manifest} is not a version=3 manifest")
    names: list[str] = []
    for line in lines[1:]:
        if not safe_member(line):
            fail(f"unsafe manifest member: {line}")
        if line in names:
            fail(f"duplicate manifest member: {line}")
        if len(names) == MAX_MEMBERS:
            fail("the manifest names more than 128 members")
        if not (root / line).is_file():
            if line.endswith(".tar.gz"):
                fail(
                    f"{line} is not in {root}.\n"
                    "The deployer embeds the appliance image, so the image has to exist before "
                    "the deployer can be built:\n    make build-arm64"
                )
            fail(f"deploy/manifest-v3.txt names {line}, which is not in {root}")
        names.append(line)
    if "deploy/transaction.sh" not in names or "deploy/manifest-v3.txt" not in names:
        fail("the manifest is missing its own transaction members")
    return names


def quote(path: pathlib.Path) -> str:
    text = str(path)
    if '"' in text or "\\" in text or "\n" in text:
        fail(f"cannot embed a path the assembler would misread: {text}")
    return f'"{text}"'


def render(root: pathlib.Path, names: list[str], fmt: str) -> str:
    if fmt == "elf":
        data_section = '.section .rodata.dp_capsule,"a"'
        table_section = '.section .data.rel.ro.dp_capsule,"aw"'
    else:
        data_section = '.section .rdata$dp_capsule,"dr"'
        table_section = '.section .rdata$dp_capsule_table,"dr"'
    out = [
        "/* @generated by tools/gen/gen_capsule.py from deploy/manifest-v3.txt. Do not edit. */",
        data_section,
    ]
    for index, name in enumerate(names):
        out += [
            ".balign 16",
            f"dp_capsule_name_{index}:",
            f'    .asciz "{name}"',
            ".balign 16",
            f"dp_capsule_data_{index}:",
            f"    .incbin {quote(root / name)}",
            f"dp_capsule_end_{index}:",
            "    .byte 0",
        ]
    for symbol, path in (
        ("dp_license_data", "LICENSE"),
        ("dp_notices_data", "THIRD_PARTY_NOTICES.txt"),
    ):
        out += [
            ".balign 16",
            f".globl {symbol}",
            f"{symbol}:",
            f"    .incbin {quote(root / path)}",
            f"{symbol}_end:",
            "    .byte 0",
        ]
    out += [table_section, ".balign 8", ".globl dp_capsule_table", "dp_capsule_table:"]
    for index in range(len(names)):
        out.append(
            f"    .quad dp_capsule_name_{index}, dp_capsule_data_{index}, "
            f"dp_capsule_end_{index} - dp_capsule_data_{index}"
        )
    out += [
        ".balign 8",
        ".globl dp_capsule_count",
        "dp_capsule_count:",
        f"    .quad {len(names)}",
        ".globl dp_license_size",
        "dp_license_size:",
        "    .quad dp_license_data_end - dp_license_data",
        ".globl dp_notices_size",
        "dp_notices_size:",
        "    .quad dp_notices_data_end - dp_notices_data",
    ]
    if fmt == "elf":
        # Without this note the linker assumes the object needs an executable
        # stack and grants one to the whole program.
        out.append('.section .note.GNU-stack,"",@progbits')
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", required=True)
    parser.add_argument("--format", choices=("elf", "pe"), required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--depfile")
    # The output is rewritten only when its text changes, and a rebuilt image
    # does not change the text, so the object assembled from it has to depend
    # on the members directly or it would keep embedding the old image.
    parser.add_argument("--object")
    arguments = parser.parse_args()
    root = pathlib.Path(arguments.root).resolve()
    names = read_members(root)
    output = pathlib.Path(arguments.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    text = render(root, names, arguments.format)
    if not output.exists() or output.read_text() != text:
        output.write_text(text)
    if arguments.depfile:
        inputs = [root / "deploy/manifest-v3.txt"] + [root / name for name in names]
        inputs += [root / "LICENSE", root / "THIRD_PARTY_NOTICES.txt"]
        targets = f"{output} {arguments.object}" if arguments.object else str(output)
        lines = [f"{targets}: " + " ".join(str(p) for p in inputs)]
        lines += [f"{p}:" for p in inputs]
        pathlib.Path(arguments.depfile).write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
