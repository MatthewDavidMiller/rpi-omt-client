//! Compiles the manifest-v3 capsule into the deployer.
//!
//! Everything the Raspberry Pi receives -- the host scripts, the OpenRC
//! services, the compose file, the legal texts, and the ARM64 image archive
//! -- is embedded, so the operator's copy of the deployer is the whole
//! appliance and needs no checkout beside it. deploy/manifest-v3.txt stays
//! the single definition of that set: this reads it and writes a table of
//! `include_bytes!` members.
//!
//! `OMT_CAPSULE_ROOT` names the tree to embed (the repository by default; a
//! fixture tree for tests). Without the image the capsule is built empty, so
//! the workspace gates run before any image exists; a release build sets
//! `OMT_CAPSULE_REQUIRED=1`, which turns a missing member into a build
//! failure.

// The manifest is the repository's own file, not outside input.
#![allow(clippy::disallowed_methods)]

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

const MAX_MEMBERS: usize = 128;

/// The same rule as core::valid_manifest_name.
fn safe_member(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= 240
        && !value.starts_with('/')
        && !value.ends_with('/')
        && !value.contains("//")
        && value.bytes().all(|b| b.is_ascii_alphanumeric() || b"._/-".contains(&b))
        && value.split('/').all(|p| !p.is_empty() && p != "." && p != "..")
}

fn members(root: &Path) -> Result<Vec<String>, String> {
    let manifest = root.join("deploy/manifest-v3.txt");
    println!("cargo:rerun-if-changed={}", manifest.display());
    let text = fs::read_to_string(&manifest)
        .map_err(|e| format!("{} is unreadable: {e}", manifest.display()))?;
    let mut lines = text.lines();
    if lines.next() != Some("version=3") {
        return Err(format!("{} is not a version=3 manifest", manifest.display()));
    }
    let mut names: Vec<String> = Vec::new();
    for line in lines {
        if !safe_member(line) {
            return Err(format!("unsafe manifest member: {line}"));
        }
        if names.iter().any(|n| n == line) {
            return Err(format!("duplicate manifest member: {line}"));
        }
        if names.len() == MAX_MEMBERS {
            return Err("the manifest names more than 128 members".into());
        }
        names.push(line.to_owned());
    }
    if !names.iter().any(|n| n == "deploy/transaction.sh")
        || !names.iter().any(|n| n == "deploy/manifest-v3.txt")
    {
        return Err("the manifest is missing its own transaction members".into());
    }
    Ok(names)
}

fn literal(path: &Path) -> Result<String, String> {
    let text = path.to_str().ok_or_else(|| format!("{} is not UTF-8", path.display()))?;
    Ok(format!("{text:?}"))
}

fn render(root: &Path, required: bool) -> Result<String, String> {
    let names = members(root)?;
    let missing: Vec<&String> = names.iter().filter(|n| !root.join(n).is_file()).collect();
    for name in &names {
        println!("cargo:rerun-if-changed={}", root.join(name).display());
    }
    let mut out = String::from(
        "// Generated by crates/omt-capsule/build.rs from deploy/manifest-v3.txt.\n\
         pub static CAPSULE: omt_deploy::capsule::Capsule = omt_deploy::capsule::Capsule {\n    \
         members: &[\n",
    );
    if let Some(first) = missing.first() {
        if required {
            if first.ends_with(".tar.gz") {
                return Err(format!(
                    "{first} is not in {}.\nThe deployer embeds the appliance image, so the image \
                     has to exist before the deployer can be built:\n    make build-arm64",
                    root.display()
                ));
            }
            return Err(format!(
                "deploy/manifest-v3.txt names {first}, which is not in {}",
                root.display()
            ));
        }
        println!("cargo:warning=building an empty capsule: {first} is not in {}", root.display());
        out.push_str("    ],\n    license: \"\",\n    notices: \"\",\n};\n");
        return Ok(out);
    }
    for name in &names {
        let _ = writeln!(
            out,
            "        omt_deploy::capsule::Member {{ name: {name:?}, bytes: include_bytes!({}) }},",
            literal(&root.join(name))?
        );
    }
    let _ = write!(
        out,
        "    ],\n    license: include_str!({}),\n    notices: include_str!({}),\n}};\n",
        literal(&root.join("LICENSE"))?,
        literal(&root.join("THIRD_PARTY_NOTICES.txt"))?
    );
    Ok(out)
}

fn main() {
    println!("cargo:rerun-if-env-changed=OMT_CAPSULE_ROOT");
    println!("cargo:rerun-if-env-changed=OMT_CAPSULE_REQUIRED");
    let root = env::var_os("OMT_CAPSULE_ROOT")
        .map_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).join("../.."), PathBuf::from);
    let root = fs::canonicalize(&root).unwrap_or(root);
    let required = env::var("OMT_CAPSULE_REQUIRED").is_ok_and(|v| v == "1");
    let Some(out_dir) = env::var_os("OUT_DIR") else {
        println!("cargo::error=OUT_DIR is not set");
        return;
    };
    match render(&root, required) {
        Ok(text) => {
            if let Err(e) = fs::write(Path::new(&out_dir).join("capsule.rs"), text) {
                println!("cargo::error=cannot write the capsule table: {e}");
            }
        }
        Err(e) => println!("cargo::error={}", e.replace('\n', " ")),
    }
}
